use zune_bmp::BmpDecoder;
use zune_core::bytestream::ZCursor;

/// A 1x1 24 bpp BI_RGB image with a 40 byte BITMAPINFOHEADER, so
/// fewer than 12 bytes follow the header
#[rustfmt::skip]
const RGB24_1X1: [u8; 58] = [
    // file header
    0x42, 0x4D, 0x3A, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x36, 0x00, 0x00, 0x00,
    // BITMAPINFOHEADER: 1x1, 24 bpp, BI_RGB, 4 bytes of pixel data
    0x28, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00,
    0x18, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x13, 0x0B, 0x00, 0x00,
    0x13, 0x0B, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // one pixel (blue, green, red) and one byte of padding
    0x10, 0x20, 0x30, 0x00
];

#[test]
fn test_rgb24_without_masks() {
    let pixels = BmpDecoder::new(ZCursor::new(&RGB24_1X1[..]))
        .decode()
        .unwrap();

    assert_eq!(pixels, [0x30, 0x20, 0x10]);
}
