use zune_bmp::BmpDecoder;
use zune_core::bytestream::ZCursor;

/// A 1x1 BI_RLE4 image whose only line ends with an end of line escape,
/// followed by the end of bitmap escape
#[rustfmt::skip]
const RLE4_EOL_ON_LAST_LINE: [u8; 68] = [
    // file header
    0x42, 0x4D, 0x44, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x3E, 0x00, 0x00, 0x00,
    // BITMAPINFOHEADER: 1x1, 4 bpp, BI_RLE4, 6 bytes of pixel data, 2 colors
    0x28, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00,
    0x04, 0x00, 0x02, 0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x13, 0x0B, 0x00, 0x00,
    0x13, 0x0B, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    // palette: blue, red
    0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0x00,
    // one pixel of index 1, end of line, end of bitmap
    0x01, 0x10, 0x00, 0x00, 0x00, 0x01
];

#[test]
fn test_rle4_end_of_line_on_last_line() {
    let pixels = BmpDecoder::new(ZCursor::new(&RLE4_EOL_ON_LAST_LINE[..]))
        .decode()
        .unwrap();

    assert_eq!(pixels, [255, 0, 0]);
}
